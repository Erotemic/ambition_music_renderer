#: The scholar tuned to the giant.
SCHOLAR_CENTS = 18.0


def midi(name: str) -> int:
    return 12 * (int(name[-1]) + 1) + NOTE[name[:-1]]


def motif(motif_id: str, bars, level=0.94, gate=0.88) -> dict:
    """A v1 motif from one list a bar of (beat, length, note), 4/4."""
    notes = sorted((4 * k + at, dur, name) for k, row in enumerate(bars) for at, dur, name in row)
    root = notes[0][2]
    onsets = [at for at, _, _ in notes] + [4.0 * len(bars)]
    return {
        "id": motif_id,
        "root": root,
        "intervals": [midi(name) - midi(root) for _, _, name in notes],
        "rhythm": [round(onsets[i + 1] - onsets[i], 4) for i in range(len(notes))],
        "durations": [round(dur * gate, 4) for _, dur, _ in notes],
        "velocities": [round(level + (0.06 if at % 1 == 0 else 0.0), 3) for at, _, _ in notes],
    }


def sixteenths(names: str, start=0.0):
    return [(start + 0.25 * i, 0.25, name) for i, name in enumerate(names.split())]


def eighths(names: str, start=0.0):
    return [(start + 0.5 * i, 0.5, name) for i, name in enumerate(names.split())]


