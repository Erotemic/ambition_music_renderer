def find(section_id: str) -> dict:
    return next(s for s in spec["sections"] if s["id"] == section_id)


def motif_layer(instruments, motif_id: str, bar: int, velocity: int) -> dict:
    return {"kind": "motif", "instruments": list(instruments), "motif": motif_id, "starts": [[bar, 0.0]],
            "velocity": velocity, "articulation": "legato", "humanize_ms": 1.6, "humanize_velocity_pct": 2}


def chord_hits(instruments, hits, duration, velocity, offsets) -> dict:
    return {"kind": "chord_hits", "instruments": instruments, "hits": hits, "duration_beats": duration, "octave": 2,
            "velocity": velocity, "articulation": "marcato", "voicing": "power", "humanize_ms": 2.0,
            "instrument_velocity_offsets": offsets, "constraints": {"max_pitch": 72}}


